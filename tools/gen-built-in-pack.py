"""Writes mod/src/hq_built_in.rs from the example pack in mod/built-in-pack/.

A native mod package carries only .rs and .toml files under src/ and has no
build script, so the example pack the mod falls back on is compiled in as Rust
string constants. Run this after editing a file of mod/built-in-pack/; a test
(hq_built_in::tests) fails while the generated file is out of date.

    python tools/gen-built-in-pack.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACK = ROOT / "mod" / "built-in-pack"
OUT = ROOT / "mod" / "src" / "hq_built_in.rs"
CRLF = chr(13) + chr(10)


def read(path: Path) -> str:
    # Git may check the files out with CRLF (core.autocrlf): keep LF.
    return path.read_bytes().decode("utf-8").replace(CRLF, "\n")


def literal(text: str) -> str:
    hashes = "#"
    while f'"{hashes}' in text:
        hashes += "#"
    return f'r{hashes}"{text}"{hashes}'


def files(folder: str) -> list[tuple[str, str]]:
    return [(p.name, read(p)) for p in sorted((PACK / folder).glob("*.json"))]


def table(name: str, doc: str, entries: list[tuple[str, str]], folder: str) -> list[str]:
    lines = [f"/// {doc}", f"pub const {name}: &[(&str, &str)] = &["]
    for file, text in entries:
        lines.append(f"    ({file!r}, {literal(text)}),".replace("'", '"', 2))
    lines.append("];")
    lines.append("")
    return lines


def main() -> None:
    settings = read(PACK / "quests.json")
    chapters = files("chapters")
    tables = files("reward_tables")
    out = [
        "// Generated by tools/gen-built-in-pack.py from mod/built-in-pack/: do not edit.",
        "// The example pack a world uses when it has no quests of its own, the",
        "// modpack none and the data packs none (unless the server turned it off).",
        "",
        "/// `quests.json`: the pack's settings.",
        f"pub const SETTINGS: &str = {literal(settings)};",
        "",
        *table("CHAPTERS", "`chapters/*.json`, by file name.", chapters, "chapters"),
        *table("TABLES", "`reward_tables/*.json`, by file name.", tables, "reward_tables"),
        "#[cfg(test)]",
        "mod tests {",
        "    use std::path::Path;",
        "",
        "    /// The generated constants are the files of mod/built-in-pack/ as they are now.",
        "    #[test]",
        "    fn the_generated_pack_is_up_to_date() {",
        '        let pack = Path::new(env!("CARGO_MANIFEST_DIR")).join("built-in-pack");',
        "        // Line endings aside: Git may check either side out with CRLF.",
        '        let lf = |text: &str| text.replace("\\r\\n", "\\n");',
        "        let read = |p: &Path| lf(&std::fs::read_to_string(p).unwrap());",
        '        assert_eq!(lf(super::SETTINGS), read(&pack.join("quests.json")), "run tools/gen-built-in-pack.py");',
        '        for (folder, entries) in [("chapters", super::CHAPTERS), ("reward_tables", super::TABLES)] {',
        "            let mut names: Vec<String> = std::fs::read_dir(pack.join(folder))",
        "                .unwrap()",
        "                .map(|e| e.unwrap().file_name().to_string_lossy().into_owned())",
        '                .filter(|n| n.ends_with(".json"))',
        "                .collect();",
        "            names.sort();",
        "            let listed: Vec<&str> = entries.iter().map(|(name, _)| *name).collect();",
        '            assert_eq!(listed, names, "run tools/gen-built-in-pack.py");',
        "            for (name, text) in entries {",
        '                assert_eq!(lf(text), read(&pack.join(folder).join(name)), "run tools/gen-built-in-pack.py");',
        "            }",
        "        }",
        "    }",
        "}",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
